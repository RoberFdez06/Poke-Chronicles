export type IconName = keyof typeof ICONS;

export const iconKey = (name: IconName) => `icon-${name}`;

/** Dibuja una cuadrícula de caracteres en `g` con píxeles de tamaño `u`, empezando en (x, y). */
export function drawPixelGrid(g: Phaser.GameObjects.Graphics, icon: PixelIcon, x = 0, y = 0, u = 1) {
  icon.rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const c = row[i];
      if (c === '.') continue;
      g.fillStyle(icon.palette[c], 1).fillRect(x + i * u, y + j * u, u, u);
    }
  });
  return g;
}

/** Crea (una vez) las texturas `icon-<nombre>` de todos los iconos, con filtro NEAREST. Llamar en create(). */
export function bakeIcons(scene: Phaser.Scene) {
  for (const name of Object.keys(ICONS) as IconName[]) {
    const key = iconKey(name);
    if (scene.textures.exists(key)) continue;
    const icon: PixelIcon = ICONS[name];
    const g = scene.make.graphics({}, false);
    drawPixelGrid(g, icon);
    g.generateTexture(key, icon.rows[0].length, icon.rows.length);
    g.destroy();
    scene.textures.get(key).setFilter(Phaser.Textures.FilterMode.NEAREST);
  }
}

/** Imagen de un icono ya escalado (por defecto x3 = 48 px). */
export function addIcon(scene: Phaser.Scene, x: number, y: number, name: IconName, scale = 3) {
  bakeIcons(scene);
  return scene.add.image(x, y, iconKey(name)).setScale(scale);
}
