import type { PixelIcon } from './icons';

/** Marco común: borde oscuro de 1 px y 12×12 píxeles de dibujo dentro. */
function badge(desc: string, palette: Record<string, number>, inner: string[]): PixelIcon {
  const edge = '................';
  const frame = '.kkkkkkkkkkkkkk.';
  const rows = [edge, frame, ...inner.map((r) => `.k${r}k.`), frame, edge];
  return { desc, palette: { k: 0x18202c, ...palette }, rows };
}

